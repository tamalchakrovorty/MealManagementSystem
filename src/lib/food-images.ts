export function getFoodImage(text: string, index: number = 0): string {
  const lower = text.toLowerCase();
  let bestMatch = "";
  for (const keyword of Object.keys(foodKeywordMap)) {
    if (lower.includes(keyword) && keyword.length > bestMatch.length) {
      bestMatch = keyword;
    }
  }
  if (bestMatch) return foodKeywordMap[bestMatch];
  return fallbackImages[index % fallbackImages.length];
}
